def run_one(source, old, new):
    """Run the suite against a copy of ingest.py with one planted bug. Returns (outcome, details):
    'survived'; 'failed' with the failing tests' names and messages; 'hung'; or 'error'."""
    if source.count(old) != 1:
        return "error", "the code to break was not found exactly once"
    # The copy's folder is a stand-in repository, so the temporary folder (TMPDIR) must be outside it:
    # the suite writes its raw transcripts there, and a raw file inside a repository must be ignored by git.
    with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as scratch:
        copy = Path(root) / "participant" / "skills" / "x" / "ingest.py"
        copy.parent.mkdir(parents=True)
        copy.write_text(source.replace(old, new), encoding="utf-8")
        env = dict(os.environ, INGEST_UNDER_TEST=str(copy), PYTHONDONTWRITEBYTECODE="1",
                   TMPDIR=scratch, TEMP=scratch, TMP=scratch)
        try:
            result = subprocess.run([sys.executable, "-B", str(TESTS / "test_ingest.py")], env=env, cwd=root,
                                    capture_output=True, text=True, timeout=TIMEOUT)
        except subprocess.TimeoutExpired:
            return "hung", []
    failed = [line[len("FAIL  "):] for line in result.stdout.splitlines() if line.startswith("FAIL  ")]
    if result.returncode == 0:
        return "survived", []
    if not failed:
        return "failed", [f"exit code {result.returncode}"]
    return "failed", failed


def run_baseline(source):
    """Run the suite against an unchanged copy, in the same setting as every planted bug."""
    with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as scratch:
        copy = Path(root) / "participant" / "skills" / "x" / "ingest.py"
        copy.parent.mkdir(parents=True)
        copy.write_text(source, encoding="utf-8")
        env = dict(os.environ, INGEST_UNDER_TEST=str(copy), PYTHONDONTWRITEBYTECODE="1",
                   TMPDIR=scratch, TEMP=scratch, TMP=scratch)
        try:
            result = subprocess.run([sys.executable, "-B", str(TESTS / "test_ingest.py")], env=env, cwd=root,
                                    capture_output=True, text=True, timeout=TIMEOUT)
        except subprocess.TimeoutExpired:
            return "hung", []
    if result.returncode == 0:
        return "survived", []
    return "failed", [line for line in result.stdout.splitlines() if line.startswith("FAIL")] or [result.stderr[-300:]]


def only_time_limits(details):
    return bool(details) and all(TIME_LIMIT in line for line in details)


def main():
    parser = argparse.ArgumentParser(description="Run every planted bug against the tests.")
    parser.add_argument("--jobs", type=int, default=max(1, min(6, (os.cpu_count() or 2) - 2)))
    args = parser.parse_args()
    source = INGEST.read_text(encoding="utf-8")
    # The unchanged script must pass the suite in this same setting first, or no result below means anything.
    outcome, details = run_baseline(source)
    if outcome != "survived":
        print(f"BASELINE  the unchanged ingest.py does not pass the tests here ({outcome}): "
              f"{'; '.join(details)[:500] if isinstance(details, list) else details}")
        print("No planted bug was run.")
        return 2
    print("BASELINE  the unchanged ingest.py passes the tests")
    outcomes = {}
    with concurrent.futures.ThreadPoolExecutor(max(1, args.jobs)) as pool:
        futures = {pool.submit(run_one, source, old, new): name for name, old, new in PLANTED}
        for future in concurrent.futures.as_completed(futures):
            outcomes[futures[future]] = future.result()
    # A time limit, or TIMEOUT, can be reached because other copies were running: run those again alone.
    again = [name for name, (outcome, details) in outcomes.items()
             if outcome == "hung" or (outcome == "failed" and only_time_limits(details))]
    alone = {}
    for name, old, new in PLANTED:
        if name in again:
            outcomes[name] = run_one(source, old, new)
            alone[name] = True
    caught = 0
    for name, _, _ in PLANTED:
        outcome, details = outcomes[name]
        if outcome == "error":
            print(f"ERROR     {name}: {details}")
        elif outcome == "survived":
            print(f"SURVIVED  {name}")
        elif outcome == "hung":
            caught += 1
            print(f"KILLED    {name}: the suite hung and was stopped after {TIMEOUT} seconds")
        else:
            caught += 1
            print(f"KILLED    {name}: {', '.join(line.split(':')[0] for line in details)}")
            if alone.get(name) and only_time_limits(details):
                print("          (caught only by a time limit, also in a run of its own)")
    print(f"\n{caught} of {len(PLANTED)} planted bugs caught")
    return 0 if caught == len(PLANTED) else 1


if __name__ == "__main__":
    sys.exit(main())
